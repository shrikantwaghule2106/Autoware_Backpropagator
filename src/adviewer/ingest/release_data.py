"""Per-release data files (NFR-2): what changes between Autoware versions lives in data.

Layout: src/adviewer/data/autoware-<release>/
  release.yaml   release name + how to detect it (package versions)
  layers.yaml    package -> layer (F8); generated by `adviewer layer-table`, plus
                 hand-written `name_rules` for packages whose repo is not in the source
Later phases add more files to the same folder (aliases, topic-valued parameters).
"""
from __future__ import annotations

from dataclasses import dataclass, field
from fnmatch import fnmatch
from pathlib import Path
from typing import Any

import yaml

from adviewer.model import Layer

from .package_xml import PackageInfo

DATA_DIR = Path(__file__).resolve().parent.parent / "data"


@dataclass
class ReleaseData:
    release: str
    folder: Path
    detect: dict[str, str]
    layers: dict[str, Layer] = field(default_factory=dict)
    name_rules: list[tuple[str, Layer]] = field(default_factory=list)

    def layer_for(self, package: str) -> Layer:
        """Generated table first, then the first matching name rule, else unknown."""
        if package in self.layers:
            return self.layers[package]
        for pattern, layer in self.name_rules:
            if fnmatch(package, pattern):
                return layer
        return Layer.unknown

    def load(self, name: str) -> Any:
        """Another data file of this release (parsed YAML), or None if it does not exist."""
        f = self.folder / name
        return yaml.safe_load(f.read_text(encoding="utf-8")) if f.is_file() else None


def _read(folder: Path) -> ReleaseData:
    rel = yaml.safe_load((folder / "release.yaml").read_text(encoding="utf-8")) or {}
    data = ReleaseData(
        release=str(rel.get("release", folder.name)),
        folder=folder,
        detect={str(k): str(v) for k, v in (rel.get("detect") or {}).items()},
    )
    lay = data.load("layers.yaml") or {}
    data.layers = {str(k): Layer(v) for k, v in (lay.get("packages") or {}).items()}
    data.name_rules = [(str(p), Layer(v)) for p, v in (lay.get("name_rules") or [])]
    return data


def version_key(version: str) -> tuple[int, ...]:
    """Releases compared as numbers, so 1.10.0 comes after 1.9.0."""
    return tuple(int(part) if part.isdigit() else -1 for part in version.replace("-", ".").split("."))


def available_releases() -> list[ReleaseData]:
    """Every release adviewer has data for, oldest first."""
    folders = [d for d in DATA_DIR.glob("autoware-*") if (d / "release.yaml").is_file()]
    return [_read(d) for d in sorted(folders, key=lambda d: version_key(d.name.removeprefix("autoware-")))]


def detect_release(packages: dict[str, PackageInfo]) -> ReleaseData | None:
    """The release whose `detect` package versions all match the ingested packages."""
    for data in available_releases():
        if data.detect and all(
            pkg in packages and packages[pkg].version == ver for pkg, ver in data.detect.items()
        ):
            return data
    return None


def apply_layers(
    packages: dict[str, PackageInfo],
    source_packages: dict[str, PackageInfo] | None,
    release: ReleaseData | None,
) -> None:
    """Fill in each package's layer: source path > own path > release table > unknown."""
    for pkg in packages.values():
        src = source_packages.get(pkg.name) if source_packages else None
        if src is not None and src.layer != Layer.unknown:
            pkg.layer = src.layer
        elif pkg.layer == Layer.unknown and release is not None:
            pkg.layer = release.layer_for(pkg.name)


def write_layer_table(
    source_packages: dict[str, PackageInfo], out: Path, keep_rules_from: Path | None = None
) -> int:
    """Write layers.yaml from the source tree's path rule; keep existing hand-written rules."""
    rules: list[Any] = []
    if keep_rules_from is not None and keep_rules_from.is_file():
        rules = (yaml.safe_load(keep_rules_from.read_text(encoding="utf-8")) or {}).get(
            "name_rules"
        ) or []
    table = {
        name: info.layer.value
        for name, info in sorted(source_packages.items())
        if info.layer != Layer.unknown
    }
    header = (
        "# package -> Autoware layer. `packages` is generated by `adviewer layer-table` from the\n"
        "# source tree (top-level directory of each package). `name_rules` are hand-written\n"
        "# (fnmatch, first match wins) for packages whose repo is not in the source companion;\n"
        "# they are name-based, so less certain than `packages`. Edit freely.\n"
    )
    body = yaml.safe_dump({"packages": table}, sort_keys=False, width=100)
    rule_lines = "".join(f'  - ["{pattern}", {layer}]\n' for pattern, layer in rules)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(header + body + "name_rules:\n" + rule_lines, encoding="utf-8")
    return len(table)
